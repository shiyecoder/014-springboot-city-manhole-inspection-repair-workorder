  order_status    VARCHAR(20) NOT NULL DEFAULT '待接单' COMMENT '待接单/处理中/待验收/返工中/已完成/已作废',
  material_cost   DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT '备件费用',
  rework_count    INT         NOT NULL DEFAULT 0 COMMENT '返工次数',
