  inspector_id BIGINT      NOT NULL COMMENT '巡检员',
  check_time   DATETIME    NOT NULL COMMENT '巡检时间',
  PRIMARY KEY (id),
  KEY idx_rec_task (task_id),
  KEY idx_rec_cover (cover_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='巡检记录';

-- ---------------- 问题上报 ----------------
